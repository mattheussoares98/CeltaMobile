import 'package:celta_inventario/core/data/models/models.dart';
import 'package:celta_inventario/core/domain/entities/entities.dart';
import 'package:collection/collection.dart';

class BSFRequestTypeModel extends BSFRequestTypeEntity {
  const BSFRequestTypeModel({
    super.code,
    super.name,
    super.description,
    super.observationsOnPrint,
    super.personalizedCode,
    super.type,
    super.operationType,
    super.generatePendencyFinancialTitle,
    super.allowAlterCostOrSalePrice,
    super.utilizeSaleLikePdvModel,
    super.insertProductAutomatically,
    super.allowsQuantityLikeProduct,
    super.groupProductsInSaleRequest,
    super.decimalPlacesForUnitValue,
    super.decimalPlacesForProductQuantity,
    super.allowUseDeliveryTax,
    super.allowUseIncrement,
    super.allowUseDiscount,
    super.allowDistribution,
    super.allowSaleOffer,
    // super.allowCovenant,//TODO should add this property and treat it
    super.considerAsStockPendency,
    super.showStockByClass,
    super.showStockByExtensibleGroup,
    super.daysOfValidity,
    super.allowFinancialIncrement,
    super.allowFinancialDiscount,
    super.userGroups,
    super.paymentFinalizations,
    super.requestPrintEditionHeaderImage,
    super.useWholePrice,
    super.useECommercePrice,
    super.unitValueType,
  });

  @override
  List<Object?> get props => [
    code,
    name,
    description,
    observationsOnPrint,
    personalizedCode,
    type,
    operationType,
    generatePendencyFinancialTitle,
    allowAlterCostOrSalePrice,
    utilizeSaleLikePdvModel,
    insertProductAutomatically,
    allowsQuantityLikeProduct,
    groupProductsInSaleRequest,
    decimalPlacesForUnitValue,
    decimalPlacesForProductQuantity,
    allowUseDeliveryTax,
    allowUseIncrement,
    allowUseDiscount,
    allowDistribution,
    allowSaleOffer,
    considerAsStockPendency,
    showStockByClass,
    showStockByExtensibleGroup,
    daysOfValidity,
    allowFinancialIncrement,
    allowFinancialDiscount,
    userGroups,
    paymentFinalizations,
    requestPrintEditionHeaderImage,
    useWholePrice,
    useECommercePrice,
    unitValueType,
  ];

  factory BSFRequestTypeModel.fromJson(Map<String, dynamic> json) =>
      BSFRequestTypeModel(
        unitValueType: PracticedPriceType.fromValue(json['UnitValueType']),
        code: json['Code'],
        name: json['Name'],
        description: json['Description'],
        observationsOnPrint: json['ObservationsOnPrint'],
        personalizedCode: json['PersonalizedCode'],
        type: json['Type'],
        operationType: OperationType.values.firstWhereOrNull(
          (e) => e.value == json['OperationType'],
        ),
        generatePendencyFinancialTitle: json['GeneratePendencyFinancialTitle'],
        allowAlterCostOrSalePrice: json['AllowAlterCostOrSalePrice'],
        utilizeSaleLikePdvModel: json['UtilizeSaleLikePdvModel'],
        insertProductAutomatically: json['InsertProductAutomatically'],
        allowsQuantityLikeProduct: json['AllowsQuantityLikeProduct'],
        groupProductsInSaleRequest: json['GroupProductsInSaleRequest'],
        decimalPlacesForUnitValue: json['DecimalPlacesForUnitValue'],
        decimalPlacesForProductQuantity:
            json['DecimalPlacesForProductQuantity'],
        allowUseDeliveryTax: json['AllowUseDeliveryTax'],
        allowUseIncrement: json['AllowUseIncrement'],
        allowUseDiscount: json['AllowUseDiscount'],
        allowDistribution: json['AllowDistribution'],
        allowSaleOffer: json['AllowSaleOffer'],
        considerAsStockPendency: json['ConsiderAsStockPendency'],
        showStockByClass: json['ShowStockByClass'],
        showStockByExtensibleGroup: json['ShowStockByExtensibleGroup'],
        daysOfValidity: json['DaysOfValidity'],
        allowFinancialIncrement: json['AllowFinancialIncrement'],
        allowFinancialDiscount: json['AllowFinancialDiscount'],
        userGroups: json['UserGroups'],
        paymentFinalizations: (json['PaymentFinalizations'] as List?)
            ?.map(
              (e) =>
                  BSFPaymentFinalizationModel.fromJson(e)
                      as BSFPaymentFinalizationEntity,
            )
            .toList(),
        requestPrintEditionHeaderImage: json['RequestPrintEditionHeaderImage'],
        useWholePrice: json['UseWholePrice'],
        useECommercePrice: json['UseECommercePrice'],
      );

  Map<String, dynamic> toJson() => {
    'Code': code,
    'Name': name,
    'Description': description,
    'ObservationsOnPrint': observationsOnPrint,
    'PersonalizedCode': personalizedCode,
    'Type': type,
    'OperationType': operationType?.value,
    'GeneratePendencyFinancialTitle': generatePendencyFinancialTitle,
    'AllowAlterCostOrSalePrice': allowAlterCostOrSalePrice,
    'UtilizeSaleLikePdvModel': utilizeSaleLikePdvModel,
    'InsertProductAutomatically': insertProductAutomatically,
    'AllowsQuantityLikeProduct': allowsQuantityLikeProduct,
    'GroupProductsInSaleRequest': groupProductsInSaleRequest,
    'DecimalPlacesForUnitValue': decimalPlacesForUnitValue,
    'DecimalPlacesForProductQuantity': decimalPlacesForProductQuantity,
    'AllowUseDeliveryTax': allowUseDeliveryTax,
    'AllowUseIncrement': allowUseIncrement,
    'AllowUseDiscount': allowUseDiscount,
    'AllowDistribution': allowDistribution,
    'AllowSaleOffer': allowSaleOffer,
    'ConsiderAsStockPendency': considerAsStockPendency,
    'ShowStockByClass': showStockByClass,
    'ShowStockByExtensibleGroup': showStockByExtensibleGroup,
    'DaysOfValidity': daysOfValidity,
    'AllowFinancialIncrement': allowFinancialIncrement,
    'AllowFinancialDiscount': allowFinancialDiscount,
    'UserGroups': userGroups,
    'PaymentFinalizations': paymentFinalizations
        ?.map((e) => BSFPaymentFinalizationModel.fromEntity(e).toJson())
        .toList(),
    'RequestPrintEditionHeaderImage': requestPrintEditionHeaderImage,
    'UseWholePrice': useWholePrice,
    'UseECommercePrice': useECommercePrice,
    'UnitValueType': unitValueType?.value,
  };

  factory BSFRequestTypeModel.fromEntity(BSFRequestTypeEntity entity) =>
      BSFRequestTypeModel(
        code: entity.code,
        name: entity.name,
        description: entity.description,
        observationsOnPrint: entity.observationsOnPrint,
        personalizedCode: entity.personalizedCode,
        type: entity.type,
        operationType: entity.operationType,
        generatePendencyFinancialTitle: entity.generatePendencyFinancialTitle,
        allowAlterCostOrSalePrice: entity.allowAlterCostOrSalePrice,
        utilizeSaleLikePdvModel: entity.utilizeSaleLikePdvModel,
        insertProductAutomatically: entity.insertProductAutomatically,
        allowsQuantityLikeProduct: entity.allowsQuantityLikeProduct,
        groupProductsInSaleRequest: entity.groupProductsInSaleRequest,
        decimalPlacesForUnitValue: entity.decimalPlacesForUnitValue,
        decimalPlacesForProductQuantity: entity.decimalPlacesForProductQuantity,
        allowUseDeliveryTax: entity.allowUseDeliveryTax,
        allowUseIncrement: entity.allowUseIncrement,
        allowUseDiscount: entity.allowUseDiscount,
        allowDistribution: entity.allowDistribution,
        allowSaleOffer: entity.allowSaleOffer,
        considerAsStockPendency: entity.considerAsStockPendency,
        showStockByClass: entity.showStockByClass,
        showStockByExtensibleGroup: entity.showStockByExtensibleGroup,
        daysOfValidity: entity.daysOfValidity,
        allowFinancialIncrement: entity.allowFinancialIncrement,
        allowFinancialDiscount: entity.allowFinancialDiscount,
        userGroups: entity.userGroups,
        paymentFinalizations: entity.paymentFinalizations
            ?.map((e) => BSFPaymentFinalizationModel.fromEntity(e))
            .toList(),
        requestPrintEditionHeaderImage: entity.requestPrintEditionHeaderImage,
        useWholePrice: entity.useWholePrice,
        useECommercePrice: entity.useECommercePrice,
        unitValueType: entity.unitValueType,
      );

  BSFRequestTypeEntity toEntity() => BSFRequestTypeEntity(
    code: code,
    name: name,
    description: description,
    observationsOnPrint: observationsOnPrint,
    personalizedCode: personalizedCode,
    type: type,
    operationType: operationType,
    generatePendencyFinancialTitle: generatePendencyFinancialTitle,
    allowAlterCostOrSalePrice: allowAlterCostOrSalePrice,
    utilizeSaleLikePdvModel: utilizeSaleLikePdvModel,
    insertProductAutomatically: insertProductAutomatically,
    allowsQuantityLikeProduct: allowsQuantityLikeProduct,
    groupProductsInSaleRequest: groupProductsInSaleRequest,
    decimalPlacesForUnitValue: decimalPlacesForUnitValue,
    decimalPlacesForProductQuantity: decimalPlacesForProductQuantity,
    allowUseDeliveryTax: allowUseDeliveryTax,
    allowUseIncrement: allowUseIncrement,
    allowUseDiscount: allowUseDiscount,
    allowDistribution: allowDistribution,
    allowSaleOffer: allowSaleOffer,
    considerAsStockPendency: considerAsStockPendency,
    showStockByClass: showStockByClass,
    showStockByExtensibleGroup: showStockByExtensibleGroup,
    daysOfValidity: daysOfValidity,
    allowFinancialIncrement: allowFinancialIncrement,
    allowFinancialDiscount: allowFinancialDiscount,
    userGroups: userGroups,
    paymentFinalizations: paymentFinalizations
        ?.map((e) => (e as BSFPaymentFinalizationModel).toEntity())
        .toList(),
    requestPrintEditionHeaderImage: requestPrintEditionHeaderImage,
    useWholePrice: useWholePrice,
    useECommercePrice: useECommercePrice,
    unitValueType: unitValueType,
  );
}
